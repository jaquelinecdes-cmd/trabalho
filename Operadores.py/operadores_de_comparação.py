# Operadores de comparação (true or false): != (diferente de), < (menor que), < (maior que) , == (igual) ,  <= , >=

numero1 = 10
numero2 = 5

print (numero1 == numero2)
print (numero1 != numero2)

print (numero1 > numero2)
print (numero1 < numero2)

print (numero1 >= numero2)
print (numero1 <= numero2)

